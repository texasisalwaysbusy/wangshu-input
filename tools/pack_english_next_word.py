"""Encode the frozen English next-word counts without changing keys or scores."""

import argparse
from hashlib import sha256
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
FAMILIES = ("n1", "n2", "n3", "n4", "n5", "n6", "g11", "g12", "g21", "g22")
WIDTHS = (1, 2, 3, 4, 5, 6, 2, 2, 3, 3)
KEY_SIZE = 7


def word_bytes(word):
    if word < 128:
        return (word,)
    return (0x80 | (word >> 8), word & 0xFF)


def fitted_groups(source, word_count):
    previous = (0,) * KEY_SIZE
    for line_number, line in enumerate(source.splitlines(), 1):
        family, *columns = line.split("\t")
        family_index = FAMILIES.index(family)
        width = WIDTHS[family_index]
        numbers = tuple(map(int, columns))
        key_words = numbers[:width]
        candidates = numbers[width + 1:]
        if (len(numbers) <= width or numbers[width] != 0 or
                not 2 <= len(candidates) <= 32 or len(candidates) % 2 or
                not all(1 <= word <= word_count for word in key_words)):
            raise ValueError(f"invalid fitted group at line {line_number}")
        key = (family_index + 1, *key_words, *((0,) * (KEY_SIZE - width - 1)))
        if key <= previous:
            raise ValueError(f"unordered or duplicate fitted key at line {line_number}")
        if (not all(1 <= word <= word_count for word in candidates[::2]) or
                not all(2 <= frequency <= 65535 for frequency in candidates[1::2]) or
                len(set(candidates[::2])) * 2 != len(candidates)):
            raise ValueError(f"invalid fitted row at line {line_number}")
        rows = [(frequency << 16) | word for word, frequency in zip(candidates[::2], candidates[1::2])]
        yield key, width + 1, rows
        previous = key


def encode(source, spec):
    blocks = []
    keys = bytearray()
    rows = []
    group_count = 0
    previous = None
    for key, size, group_rows in fitted_groups(source, spec["english_word_count"]):
        if group_count % spec["block_groups"] == 0:
            blocks.append((key, len(keys), len(rows)))
            shared = KEY_SIZE
        else:
            shared = next(index for index, value in enumerate(key) if value != previous[index])
        keys.append((shared << 4) | (len(group_rows) - 1))
        for value in key[shared:size]:
            keys.extend(word_bytes(value))
        rows.extend(group_rows)
        previous = key
        group_count += 1
    if group_count != spec["groups"] or len(rows) != spec["rows"]:
        raise ValueError("fitted group or row count changed")
    size = 24 * len(blocks) + len(keys) + 4 * len(rows)
    if size > spec["static_byte_limit"]:
        raise ValueError(f"English table uses {size} bytes, above the static byte budget")
    return blocks, keys, rows, size


def render(blocks, keys, rows, spec):
    lines = [
        "// Generated by tools/pack_english_next_word.py from frozen fitted counts.",
        f"inline constexpr size_t longEnglishBlockGroups = {spec['block_groups']};",
        f"inline constexpr size_t longEnglishWordCount = {spec['english_word_count']};",
        f"inline constexpr size_t longEnglishByteLimit = {spec['static_byte_limit']};",
        "inline constexpr Block longEnglishBlocks[] = {",
    ]
    for key, offset, row in blocks:
        key_values = ", ".join(map(str, key))
        lines.append(f"    {{{{{key_values}}}, {offset}, {row}}},")
    lines.append("};")
    for descriptor, numbers, line_size in (("uint8_t longEnglishKeys", keys, 24),
                                            ("uint32_t longEnglishRows", rows, 8)):
        lines.append(f"inline constexpr {descriptor}[] = {{")
        for start in range(0, len(numbers), line_size):
            lines.append("    " + ", ".join(map(str, numbers[start:start + line_size])) + ",")
        lines.append("};")
    return ("\n".join(lines) + "\n").encode("ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("fitted_tsv", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true", help="verify existing output without writing")
    args = parser.parse_args()
    spec = json.loads((ROOT / "data/ENGLISH-NEXT-WORD-SOURCE.json").read_text(encoding="utf-8"))
    base = (ROOT / "core/context_prediction_data.inc").read_text(encoding="utf-8")
    if sha256(base.encode("utf-8")).hexdigest() != spec["base_context_source_lf_sha256"]:
        parser.error("base context source changed; verify the fitted word ID mapping first")
    source = args.fitted_tsv.read_bytes()
    if sha256(source).hexdigest() != spec["fitted_gain_tsv_sha256"]:
        parser.error("fitted input hash does not match its source manifest")
    blocks, keys, rows, size = encode(source.decode("ascii"), spec)
    result = render(blocks, keys, rows, spec)
    if args.check:
        if args.output.read_bytes() != result:
            parser.error("existing output differs from deterministic encoding")
    else:
        with args.output.open("xb") as output:
            output.write(result)
    print(f"{len(blocks)} blocks, {size} static bytes, SHA-256 {sha256(result).hexdigest()}")


if __name__ == "__main__":
    main()
